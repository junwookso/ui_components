import { afterEach, describe, expect, it, vi } from 'vitest'
import { enableAutoUnmount, mount } from '@vue/test-utils'
import { defineComponent, h, nextTick } from 'vue'
import { UINotifyProvider, useNotify } from '../src'
import type { UINotifyService } from '../src'
enableAutoUnmount(afterEach)
afterEach(() => { vi.useRealTimers(); vi.restoreAllMocks(); document.body.innerHTML = '' })
function setup() {
  vi.useFakeTimers()
  let service!: UINotifyService
  const Child = defineComponent({ setup() { service = useNotify(); return () => h('button', { id: 'trigger' }, '저장') } })
  const wrapper = mount(UINotifyProvider, { attachTo: document.body, slots: { default: () => h(Child) } })
  return { wrapper, service }
}
describe('notify action', () => {
  it('escapes text, announces by urgency, rejects blanks and defaults to five seconds', async () => {
    const { wrapper, service } = setup()
    expect(service.notify({ message: '  ' })).toBeNull()
    service.notify({ message: '<b>저장됨</b>', type: 'success' })
    service.notify({ title: '실패', message: '다시 시도', type: 'error' })
    service.notify({ message: '주의 필요', type: 'warning' })
    await nextTick(); await nextTick()
    expect(wrapper.find('b').exists()).toBe(false)
    expect(wrapper.get('[role="status"]').text()).toContain('<b>저장됨</b>')
    expect(wrapper.get('[role="alert"]').text()).toContain('실패. 다시 시도')
    await vi.advanceTimersByTimeAsync(5000)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(2)
    await vi.advanceTimersByTimeAsync(60000)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(2)
  })
  it('starts queued timers only after display and supports dismissal and clear', async () => {
    const { wrapper, service } = setup()
    const ids = Array.from({ length: 5 }, (_, i) => service.notify({ message: String(i), duration: 1000 })!)
    await nextTick()
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(3)
    expect(wrapper.get('.ui-notify-pending').text()).toContain('2개')
    service.dismiss(ids[4]!)
    await vi.advanceTimersByTimeAsync(1000)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(1)
    expect(wrapper.get('.ui-notify-message').text()).toBe('3')
    await vi.advanceTimersByTimeAsync(999)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(1)
    service.clear()
    expect(vi.getTimerCount()).toBe(0)
    await nextTick()
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(0)
  })
  it('pauses the remaining time for hover, focus and hidden documents', async () => {
    const { wrapper, service } = setup()
    service.notify({ message: '작업 완료', duration: 1000 })
    await nextTick()
    await vi.advanceTimersByTimeAsync(400)
    await wrapper.get('.ui-notify-region').trigger('pointerenter')
    const close = wrapper.get<HTMLButtonElement>('.ui-notify-close')
    close.element.focus()
    await wrapper.get('.ui-notify-region').trigger('pointerleave')
    await vi.advanceTimersByTimeAsync(5000)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(1)
    wrapper.get<HTMLButtonElement>('#trigger').element.focus()
    const hidden = vi.spyOn(document, 'hidden', 'get').mockReturnValue(true)
    document.dispatchEvent(new Event('visibilitychange'))
    await vi.advanceTimersByTimeAsync(5000)
    hidden.mockReturnValue(false)
    document.dispatchEvent(new Event('visibilitychange'))
    await vi.advanceTimersByTimeAsync(599)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(1)
    await vi.advanceTimersByTimeAsync(1)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(0)
  })
  it('keeps trigger focus on open, moves focus on dismissal and resets pauses after clearing', async () => {
    const { wrapper, service } = setup()
    const trigger = wrapper.get<HTMLButtonElement>('#trigger').element
    trigger.focus()
    service.notify({ message: '첫째', duration: 0 })
    service.notify({ message: '둘째', duration: 0 })
    await nextTick()
    expect(document.activeElement).toBe(trigger)
    wrapper.get<HTMLButtonElement>('.ui-notify-close').element.focus()
    await wrapper.get('.ui-notify-close').trigger('click')
    await nextTick()
    expect(document.activeElement).toBe(wrapper.get('.ui-notify-close').element)
    await wrapper.get('.ui-notify-region').trigger('pointerenter')
    service.clear()
    await nextTick()
    expect(document.activeElement).toBe(trigger)
    service.notify({ message: '새 알림', duration: 100 })
    await vi.advanceTimersByTimeAsync(100)
    expect(wrapper.findAll('.ui-notify-card')).toHaveLength(0)
  })
  it('isolates providers and cleans up timers and late asynchronous calls', async () => {
    const one = setup()
    const two = setup()
    one.service.notify({ message: '하나', duration: Number.NaN })
    await nextTick()
    expect(two.wrapper.findAll('.ui-notify-card')).toHaveLength(0)
    expect(vi.getTimerCount()).toBe(1)
    one.wrapper.unmount()
    expect(vi.getTimerCount()).toBe(0)
    expect(one.service.notify({ message: '늦은 응답' })).toBeNull()
  })
})
