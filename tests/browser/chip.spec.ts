import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
const story = (name: string) => `/iframe.html?id=components-uichip--${name}&viewMode=story`

test('removal supports keyboard activation and restores focus through the list', async ({ page }) => {
  await page.goto(story('removable'))
  const first = page.getByRole('button', { name: '플랫폼팀 제거' })
  await first.focus()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Shift+Tab')
  await expect(first).toHaveCSS('outline-width', '2px')
  await page.keyboard.press('Enter')
  await expect(first).toHaveCount(0)
  await expect(page.getByRole('button', { name: '진행 중 제거' })).toBeFocused()
  await expect(page.getByRole('status')).toHaveText('플랫폼팀 조건을 제거했습니다.')
  await page.keyboard.press('Space')
  await expect(page.getByRole('button', { name: '이번 달 제거' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: '조건 초기화' })).toBeFocused()
  await expect(page.getByText('적용된 조건이 없습니다.')).toBeVisible()
  await page.keyboard.press('Enter')
  await expect(page.locator('.ui-chip')).toHaveCount(3)
})

test('sizes, disabled behavior, theme colors and long labels', async ({ page }) => {
  await page.goto('/iframe.html?id=components-uichip--docs&viewMode=docs')
  const defaultChip = page.locator('.ui-chip[data-variant="default"]').first()
  await expect(defaultChip).toHaveCSS('background-color', 'rgb(244, 244, 245)')
  await expect(defaultChip).toHaveCSS('border-top-color', 'rgb(212, 212, 216)')
  await expect(defaultChip).toHaveCSS('border-top-width', '1px')
  await page.screenshot({ path: 'test-results/chip-docs.png', fullPage: true })
  await page.goto(story('sizes-and-icons'))
  await expect(page.locator('.ui-chip[data-size="sm"]')).toHaveCSS('min-height', '28px')
  await expect(page.locator('.ui-chip').nth(1)).toHaveCSS('min-height', '32px')
  await expect(page.getByRole('button', { name: '고정된 조건 제거' })).toBeDisabled()
  await page.getByRole('button', { name: '기본 Chip 제거' }).focus()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '고정된 조건 제거' })).not.toBeFocused()
  await expect(page.locator('.ui-chip-icon svg')).toHaveCSS('width', '16px')
  await page.goto(story('variants') + '&globals=theme:ocean')
  await expect(page.locator('[data-variant="primary"]')).toHaveCSS('background-color', 'rgb(3, 105, 161)')
  await expect(page.locator('[data-variant="success"]')).toHaveCSS('background-color', 'rgb(240, 253, 244)')
  await page.screenshot({ path: 'test-results/chip-variants.png', fullPage: true })
  await page.setViewportSize({ width: 320, height: 800 })
  await page.goto(story('long-label'))
  await expect(page.locator('.ui-chip')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const box = (await page.locator('.ui-chip').boundingBox())!
  const removeBox = (await page.getByRole('button').boundingBox())!
  expect(removeBox.width).toBe(24)
  expect(removeBox.x + removeBox.width).toBeLessThanOrEqual(box.x + box.width)
  await page.screenshot({ path: 'test-results/chip-long-label.png', fullPage: true })
})

test('packaged chip styles work without Preflight and removal does not submit forms', async ({ page }) => {
  await page.goto(story('sizes-and-icons'))
  await expect(page.locator('.ui-chip').first()).toBeVisible()
  const markup = await page.locator('.ui-chip').nth(1).evaluate(el => el.outerHTML)
  await page.goto('about:blank')
  await page.setContent(`<form>${markup}</form>`)
  await page.addStyleTag({ content: await readFile('.test-consumer/no-reset.css', 'utf8') })
  await page.locator('form').evaluate(el => el.addEventListener('submit', event => { event.preventDefault(); el.setAttribute('data-submitted', 'true') }))
  const button = page.getByRole('button')
  await expect(page.locator('.ui-chip')).toHaveCSS('display', 'inline-flex')
  await expect(page.locator('.ui-chip')).toHaveCSS('font-size', '14px')
  await expect(page.locator('.ui-chip')).toHaveCSS('border-top-color', 'rgb(212, 212, 216)')
  await expect(page.locator('.ui-chip')).toHaveCSS('background-color', 'rgb(244, 244, 245)')
  await expect(button).toHaveCSS('height', '24px')
  await expect(button).toHaveCSS('box-sizing', 'border-box')
  await button.focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('form')).not.toHaveAttribute('data-submitted', 'true')
  await page.emulateMedia({ forcedColors: 'active' })
  await expect(page.locator('.ui-chip')).toHaveCSS('border-top-style', 'solid')
  await page.goto('http://127.0.0.1:6008')
  await expect(page.locator('.ui-chip')).toHaveCSS('display', 'inline-flex')
  await expect(page.getByRole('button', { name: '배포 Chip 제거' })).toBeVisible()
})
