import { expect, test } from '@playwright/test'
const story = (name: string) => `/iframe.html?id=components-uitree--${name}&viewMode=story`

test('tree keyboard traversal, selection, disclosure and disabled behavior', async ({ page }) => {
  await page.goto(story('organization'))
  const company = page.getByRole('treeitem', { name: '회사', exact: true })
  const team = page.getByRole('treeitem', { name: '개발본부', exact: true })
  const platform = page.getByRole('treeitem', { name: '플랫폼팀', exact: true })
  await company.focus()
  await page.keyboard.press('ArrowRight')
  await expect(team).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(platform).toBeFocused()
  await expect(platform).toHaveAttribute('aria-selected', 'false')
  await page.keyboard.press('Space')
  await expect(platform).toHaveAttribute('aria-selected', 'true')
  await expect(platform.locator('.ui-tree-row')).toHaveCSS('outline-width', '2px')
  await page.keyboard.press('ArrowLeft')
  await expect(team).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(platform).toHaveCount(0)
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('treeitem', { name: '디자인팀', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('treeitem', { name: '보관된 조직', exact: true })).toBeFocused()
  await team.locator(':scope > .ui-tree-row .ui-tree-toggle').click()
  await expect(platform).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByRole('treeitem', { name: '인사팀 (접근 권한 없음)' })).toHaveAttribute('aria-disabled', 'true')
})
