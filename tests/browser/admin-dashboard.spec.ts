test('admin dashboard scrolls the sidebar and body independently with the footer in the body', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 180 })
  await page.goto(story)

  const sidebar = page.getByRole('complementary', { name: '운영 포털 사이드바' })
  const content = page.getByRole('group', { name: '대시보드 본문 영역' })
  const topbar = page.getByRole('banner', { name: '운영 포털 상단 바' })
  const footer = content.getByRole('contentinfo')
  const sidebarOffset = () => sidebar.evaluate(element => element.scrollTop)
  const contentOffset = () => content.evaluate(element => element.scrollTop)
  await expect(footer).toBeAttached()
  await expect(footer).toHaveCSS('height', '48px')
  await expect(footer).not.toBeInViewport()

  await sidebar.hover()
  await page.mouse.wheel(0, 160)
  await expect.poll(sidebarOffset).toBeGreaterThan(0)
  expect(await contentOffset()).toBe(0)
  const scrolledSidebar = await sidebarOffset()

  await content.focus()
  await page.keyboard.press('End')
  await expect(footer).toBeInViewport({ ratio: 1 })
  await expect(topbar).toBeInViewport({ ratio: 1 })
  expect(await contentOffset()).toBeGreaterThan(0)
  expect(await sidebarOffset()).toBe(scrolledSidebar)
  expect(await page.evaluate(() => window.scrollY)).toBe(0)

  await footer.getByRole('link', { name: '대시보드로 이동' }).click()
  await expect(page.getByRole('heading', { name: '운영 대시보드' })).toBeFocused()
  await expect(footer).not.toBeInViewport()
})
