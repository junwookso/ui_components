  await expect(lineChart.locator('svg path[stroke-dasharray][stroke="var(--ui-chart-2)"]')).toBeVisible()
  await expect(lineChart).toHaveAccessibleName(/22일 누적 접수 150건, 누적 완료 121건/)
  await expect(pieChart.locator('svg path[fill^="var(--ui-chart-"]')).toHaveCount(3)
  await expect(pieChart).toHaveAccessibleName(/접수 2건, 처리 중 3건, 완료 3건/)
  await expect(page.locator('.admin-metric-icon[aria-hidden="true"]')).toHaveCount(4)
  const intakeCard = page.getByRole('region', { name: '접수 건수' })
  const icon = intakeCard.locator('.admin-metric-icon')
  const value = intakeCard.getByText('150', { exact: true })
  await expect(icon).toHaveCSS('width', '84px')
