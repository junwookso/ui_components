test('admin dashboard moves focus from the mobile drawer and contains table overflow', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto(story)

  const topbar = page.getByRole('banner', { name: '운영 포털 상단 바' })
  await expect(topbar).toHaveCSS('height', '49px')
  await expect(page.getByRole('contentinfo')).toHaveCSS('height', '82px')
  const intake = page.getByRole('region', { name: '접수 건수' })
  const icon = (await intake.locator('.admin-metric-icon').boundingBox())!
  const value = (await intake.getByText('150', { exact: true }).boundingBox())!
  expect(icon.width).toBeGreaterThan(28)
  expect(icon.width).toBeLessThan(84)
  expect(icon.x + icon.width).toBeLessThan(value.x)
  const menu = page.getByRole('button', { name: '메뉴', exact: true })
  await menu.focus()
  await page.keyboard.press('Enter')
  const drawer = page.getByRole('dialog', { name: '운영 관리 메뉴' })
  const requestGroup = drawer.getByRole('button', { name: '요청 관리' })
  const requestsLink = drawer.getByRole('link', { name: '업무 요청' })
  await expect(requestGroup).toHaveAttribute('aria-expanded', 'false')
  await expect(requestsLink).toBeHidden()
  await requestGroup.press('Space')
  await expect(requestsLink).toBeVisible()
  await requestsLink.focus()
  await page.keyboard.press('Enter')
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('heading', { name: '업무 요청' }).locator('[tabindex="-1"]')).toBeFocused()

  const tableArea = page.getByRole('region', { name: '요청 목록 표 영역' })
  expect(await tableArea.evaluate(element => element.scrollWidth)).toBeGreaterThan(await tableArea.evaluate(element => element.clientWidth))
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(360)

  await menu.click()
  await expect(drawer).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect(drawer).toBeHidden()
  await expect(topbar).toHaveCSS('height', '49px')
  const sidebar = page.getByRole('complementary')
  await expect(sidebar).toHaveCSS('overflow-y', 'auto')
  await expect(sidebar).toHaveCSS('width', '288px')
  const current = sidebar.getByRole('link', { name: '업무 요청' })
  await expect(current).toHaveAttribute('aria-current', 'page')
  await expect(current).toBeFocused()
})

