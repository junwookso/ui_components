  await expect(footer).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
  await expect(footer).toHaveCSS('color', 'rgb(145, 152, 161)')
  await expect(footerLink).toHaveCSS('color', 'rgb(145, 152, 161)')
  await expect(metric.getByText('접수 건수', { exact: true })).toHaveCSS('color', 'rgb(145, 152, 161)')
  await expect(metricIcon).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
