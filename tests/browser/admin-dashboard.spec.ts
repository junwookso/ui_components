  await expect(sidebar).toHaveCSS('background-color', 'rgb(43, 43, 46)')
  await expect(selectedNavRow).toHaveCSS('background-color', 'rgb(212, 212, 216)')
  await expect(selectedNavRow.getByText('대시보드', { exact: true })).toHaveCSS('color', 'rgb(31, 35, 40)')
  await expect(unselectedNavLabel).toHaveCSS('color', 'rgb(145, 152, 161)')
  await expect(heading).toHaveCSS('color', 'rgb(240, 246, 252)')
  await expect(requestTable).toHaveCSS('color', 'rgb(240, 246, 252)')
  await expect(topbar).toHaveCSS('background-color', 'rgb(79, 107, 150)')
