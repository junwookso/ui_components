import { expect, test } from '@playwright/test'
const story = '/iframe.html?id=layout-basic-layout--responsive&viewMode=story'

test('desktop layout keeps menu, topbar and footer visible while only main scrolls', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto(story)
  const sidebar = page.getByRole('complementary', { name: '서비스 메뉴' })
  await expect(sidebar).toBeVisible()
  await expect(page.getByRole('button', { name: '메뉴 열기' })).toHaveCount(0)
  await expect(page.getByRole('dialog')).toBeHidden()
  const header = (await page.getByRole('banner').boundingBox())!
  const footer = (await page.getByRole('contentinfo').boundingBox())!
  const menu = (await sidebar.boundingBox())!
  const main = page.getByRole('main')
  const content = (await main.boundingBox())!
  expect(header.y).toBe(0)
  expect(footer.y + footer.height).toBe(800)
  expect(content.x).toBe(menu.x + menu.width)
  await main.evaluate(el => { el.scrollTop = 400 })
  expect(await main.evaluate(el => el.scrollTop)).toBe(400)
  expect((await page.getByRole('banner').boundingBox())!.y).toBe(header.y)
  expect((await sidebar.boundingBox())!.y).toBe(menu.y)
  expect((await page.getByRole('contentinfo').boundingBox())!.y).toBe(footer.y)
  expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBe(800)
  await sidebar.getByRole('link', { name: '프로젝트', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('프로젝트')
  await expect(main).toBeFocused()
  expect(await main.evaluate(el => el.scrollTop)).toBe(0)
  await page.screenshot({ path: 'test-results/basic-layout-desktop.png' })
})

test('mobile overlay closes on navigation and Escape, with no duplicate visible menu', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(story + '&globals=theme:ocean')
  const trigger = page.getByRole('button', { name: '메뉴 열기' })
  await expect(trigger).toBeVisible()
  await expect(page.getByRole('complementary')).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: '업무 메뉴' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({ path: 'test-results/basic-layout-mobile.png' })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: '서비스 메뉴' })
  await expect(drawer).toBeVisible()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('body')).toHaveCSS('overflow', 'hidden')
  await page.screenshot({ path: 'test-results/basic-layout-overlay.png' })
  await drawer.getByRole('link', { name: '보고서', exact: true }).click()
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('보고서')
  await expect(page.getByRole('main')).toBeFocused()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await trigger.click()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
})

test('crossing breakpoint closes overlay, preserves selection and moves focus to a visible control', async ({ page }) => {
  await page.setViewportSize({ width: 1023, height: 800 })
  await page.goto(story)
  const trigger = page.getByRole('button', { name: '메뉴 열기' })
  await trigger.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.setViewportSize({ width: 1024, height: 800 })
  await expect(page.getByRole('dialog')).toBeHidden()
  const current = page.getByRole('complementary').getByRole('link', { name: '내 업무', exact: true })
  await expect(current).toBeFocused()
  await expect(page.locator('body')).not.toHaveCSS('overflow', 'hidden')
  await page.setViewportSize({ width: 1023, height: 800 })
  await expect(trigger).toBeFocused()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('dialog')).toBeHidden()
  await trigger.click()
  await expect(page.getByRole('dialog').getByRole('link', { name: '내 업무', exact: true })).toHaveAttribute('aria-current', 'page')
})
