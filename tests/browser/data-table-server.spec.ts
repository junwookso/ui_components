import { expect, test } from '@playwright/test'

const story = '/iframe.html?id=components-uidatatable--server&viewMode=story'

test('server pagination and sorting request the relevant rows and retain selection by ID', async ({ page }) => {
  await page.goto(story)
  const table = page.getByRole('table', { name: '서버 직원 목록' })
  const summary = page.getByRole('status')
  const next = page.getByRole('button', { name: '다음', exact: true })
  const firstRow = table.getByRole('row').nth(1)
  await expect(summary).toContainText('총 12건 중 1–5건')
  await table.getByRole('checkbox', { name: '김민수 선택' }).check()
  await expect(summary).toContainText('현재 응답에서 1건 선택')
  await next.click()
  await expect(summary).toContainText('총 12건 중 6–10건')
  await expect(summary).toContainText('현재 응답에서 0건 선택')
  await expect(firstRow).toContainText('강하은')

  await table.getByRole('button', { name: '프로젝트 수: 오름차순 정렬' }).click()
  await expect(summary).toContainText('총 12건 중 1–5건')
  await expect(firstRow).toContainText('김민수')
  await expect(table.getByRole('row').nth(2)).toContainText('오시우')
  await expect(table.getByRole('checkbox', { name: '김민수 선택' })).toBeChecked()
})

test('a late response cannot replace the latest search and the results can be empty', async ({ page }) => {
  const now = new Date('2026-11-24T12:00:00Z')
  await page.clock.install({ time: now })
  await page.goto(story)
  const summary = page.getByRole('status')
  const table = page.getByRole('table', { name: '서버 직원 목록' })
  const search = page.getByRole('searchbox', { name: '서버 직원 목록 검색' })
  await expect(summary).toContainText('총 12건 중 1–5건')
  await page.clock.pauseAt(new Date(now.getTime() + 30_000))
  await page.getByRole('button', { name: '응답 순서 체험' }).press('Enter')
  await expect(search).toHaveValue('플랫폼')
  await expect(summary).toHaveText('데이터를 불러오는 중입니다.')
  await page.clock.fastForward(100)
  await expect(search).toHaveValue('이서연')
  await page.clock.fastForward(250)
  await expect(summary).toContainText('총 1건 중 1–1건')
  await expect(table.getByRole('cell', { name: '이서연', exact: true })).toBeVisible()
  await page.clock.fastForward(900)
  await expect(summary).toContainText('총 1건 중 1–1건')
  await expect(table.getByRole('cell', { name: '이서연', exact: true })).toBeVisible()
  await expect(table.getByRole('cell', { name: '김민수', exact: true })).toHaveCount(0)

  await search.fill('일치하지 않는 이름')
  await expect(summary).toHaveText('데이터를 불러오는 중입니다.')
  await page.clock.fastForward(250)
  await expect(table.getByText('검색 결과가 없습니다. 검색어를 변경해 주세요.')).toBeVisible()
  await expect(summary).toContainText('총 0건 중 0–0건')
})

test('a failed request can retry the same page and the table scrolls at narrow widths', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 820 })
  await page.goto(story)
  const table = page.getByRole('table', { name: '서버 직원 목록' })
  const summary = page.getByRole('status')
  const region = page.getByRole('region', { name: '서버 직원 목록 표 영역' })
  await expect(summary).toContainText('총 12건 중 1–5건')
  await page.getByRole('button', { name: '다음', exact: true }).click()
  await expect(summary).toContainText('총 12건 중 6–10건')
  await page.getByRole('button', { name: '조회 실패 체험' }).click()
  await expect(summary).toHaveText('직원 목록을 불러오지 못했습니다. 다시 시도해 주세요.')
  await expect(page.getByText('2 / 3 페이지')).toBeVisible()
  await expect(table.getByRole('cell', { name: '강하은', exact: true })).toHaveCount(0)
  await table.getByRole('button', { name: '다시 시도' }).click()
  await expect(region).toBeFocused()
  await expect(summary).toContainText('총 12건 중 6–10건')
  await expect(table.getByRole('cell', { name: '강하은', exact: true })).toBeVisible()
  expect(await region.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
