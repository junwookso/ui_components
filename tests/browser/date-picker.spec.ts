import { expect, test } from '@playwright/test'
const story = (name: string) => `/iframe.html?id=components-uidatepicker--${name}&viewMode=story`

test('date and month inputs update calendar strings, accept leap days and clear', async ({ page }) => {
  await page.goto(story('levels'))
  const day = page.getByLabel('기준일', { exact: true })
  const month = page.getByLabel('조회 월', { exact: true })
  await expect(day).toHaveAttribute('type', 'date')
  await expect(month).toHaveAttribute('type', 'month')
  await day.fill('2028-02-29')
  await month.fill('2027-01')
  await expect(page.getByTestId('day-value')).toHaveText('선택한 날짜: 2028-02-29')
  await expect(page.getByTestId('month-value')).toHaveText('선택한 월: 2027-01')
  await day.focus()
  await expect(day).toHaveCSS('border-top-width', '2px')
  await page.keyboard.press('ArrowUp')
  await expect(day).not.toHaveValue('2028-02-29')
  await page.getByRole('button', { name: '초기화' }).click()
  await expect(day).toHaveValue('')
  await expect(month).toHaveValue('')
})

test('required fields and inclusive min/max prevent invalid form submission', async ({ page }) => {
  await page.goto(story('form'))
  const day = page.getByLabel('신청일 (필수)'), month = page.getByLabel('정산 월 (필수)')
  await page.getByRole('button', { name: '적용' }).click()
  await expect(page.getByRole('status')).toBeEmpty()
  await expect(day).toBeFocused()
  await day.fill('2019-12-31')
  await month.fill('2036-01')
  expect(await day.evaluate(el => (el as HTMLInputElement).validity.rangeUnderflow)).toBe(true)
  expect(await month.evaluate(el => (el as HTMLInputElement).validity.rangeOverflow)).toBe(true)
  await page.getByRole('button', { name: '적용' }).click()
  await expect(page.getByRole('status')).toBeEmpty()
  await day.fill('2020-01-01')
  await month.fill('2035-12')
  await page.getByRole('button', { name: '적용' }).click()
  await expect(page.getByRole('status')).toHaveText('2020-01-01 / 2035-12')
  expect(await page.locator('form').evaluate(el => Object.fromEntries(new FormData(el as HTMLFormElement)))).toEqual({ day: '2020-01-01', month: '2035-12' })
})
