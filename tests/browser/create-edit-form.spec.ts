import { expect, test } from '@playwright/test'

const story = (name: string) => `/iframe.html?id=patterns-create-and-edit-form--${name}&viewMode=story`

test('registration validates required fields, locks the form while saving and keeps the saved values', async ({ page }) => {
  await page.goto(story('create-request'))
  const title = page.getByRole('textbox', { name: '요청 제목', exact: true })
  const team = page.getByRole('combobox', { name: '담당 팀', exact: true })
  const details = page.getByRole('textbox', { name: '요청 내용' })
  const save = page.getByRole('button', { name: '저장', exact: true })
  const cancel = page.getByRole('button', { name: '취소', exact: true })
  const status = page.getByRole('status')

  await expect(page.getByRole('heading', { level: 1 })).toHaveText('업무 요청 등록')
  await expect(title).not.toHaveAttribute('aria-invalid')
  await title.fill('   ')
  await save.click()
  await expect(title).toBeFocused()
  await expect(title).toHaveAccessibleDescription('요청 제목을 입력해 주세요.')
  await expect(team).toHaveAccessibleDescription('담당 팀을 선택해 주세요.')
  await page.getByRole('link', { name: '담당 팀을 선택해 주세요.' }).press('Enter')
  await expect(team).toBeFocused()

  await title.fill(' 업무 포털 권한 신청 ')
  await team.selectOption('operations')
  await details.fill('검토 대상\n운영지원팀')
  await expect(title).not.toHaveAttribute('aria-invalid')
  await expect(team).not.toHaveAttribute('aria-invalid')
  await expect(page.getByText('입력 내용을 확인해 주세요.')).toHaveCount(0)

  const now = new Date('2026-11-24T12:00:00Z')
  await page.clock.install({ time: now })
  await page.clock.pauseAt(new Date(now.getTime() + 1000))
  await save.press('Enter')
  const saving = page.getByRole('button', { name: '저장 중', exact: true })
  await expect(saving).toBeDisabled()
  await expect(saving).toHaveAttribute('aria-busy', 'true')
  for (const control of [title, team, details, cancel]) {
    await expect(control).toBeDisabled()
  }
  await expect(status).toHaveText('저장 중입니다.')
  await page.locator('form').dispatchEvent('submit')
  await expect(status).toHaveText('저장 중입니다.')

  await page.clock.fastForward(800)
  await expect(status).toHaveText('업무 요청을 등록했습니다.')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('업무 요청 수정')
  await expect(title).toHaveValue('업무 포털 권한 신청')
  await expect(team).toHaveValue('operations')
  await expect(details).toHaveValue('검토 대상\n운영지원팀')
  await expect(save).toBeEnabled()
})

test('a service error preserves the draft for retry and confirmed navigation discards unsaved edits', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 760 })
  await page.goto(story('save-failure'))
  const title = page.getByRole('textbox', { name: '요청 제목', exact: true })
  const team = page.getByRole('combobox', { name: '담당 팀', exact: true })
  const save = page.getByRole('button', { name: '저장', exact: true })
  const leave = page.getByRole('button', { name: '업무 요청 목록으로' })
  const error = page.getByRole('group', { name: '저장 오류' })

  await title.fill('재시도할 제목')
  await team.selectOption('finance')
  await save.click()
  await expect(leave).toBeDisabled()
  await expect(error).toBeFocused()
  await expect(error).toHaveAccessibleDescription(/입력한 내용은 유지됩니다/)
  await expect(title).not.toHaveAttribute('aria-invalid')
  await expect(title).toHaveValue('재시도할 제목')
  await expect(team).toHaveValue('finance')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await save.click()
  await expect(page.getByRole('status')).toHaveText('변경사항을 저장했습니다.')
  await expect(error).toHaveCount(0)

  await title.fill('아직 저장하지 않은 제목')
  await leave.press('Enter')
  const dialog = page.getByRole('dialog', { name: '저장하지 않은 변경사항을 버릴까요?' })
  await expect(dialog.getByRole('button', { name: '계속 편집' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(leave).toBeFocused()
  await expect(title).toHaveValue('아직 저장하지 않은 제목')

  await leave.click()
  await dialog.getByRole('button', { name: '변경사항 버리기' }).click()
  await expect(page).toHaveURL(/path=\/story\/patterns-list-search--requests/)
})
