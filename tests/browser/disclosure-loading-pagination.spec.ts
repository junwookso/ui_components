  await navigation.getByRole('button', { name: '11 페이지' }).click()
  await next.press('Enter')
  const current = navigation.getByRole('button', { name: '12 페이지' })
  await expect(current).toHaveAttribute('aria-current', 'page')
  await expect(current).toBeFocused()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.goto(story('uipagination--disabled'))
  await expect(navigation.getByRole('button', { name: '2 페이지', exact: true })).toBeDisabled()
