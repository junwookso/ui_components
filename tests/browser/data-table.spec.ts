import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

const story = (name: string) => `/iframe.html?id=components-uidatatable--${name}&viewMode=story`

test('keyboard sorting, page selection, pagination and search work together', async ({ page }) => {
  await page.goto(story('employees'))
  const table = page.getByRole('table', { name: '직원 목록' })
  await expect(table).toBeVisible()
  await expect(table.locator('tbody tr')).toHaveCount(10)
  const sort = page.getByRole('button', { name: '이름: 오름차순 정렬' })
  await sort.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('columnheader').filter({ has: page.getByRole('button', { name: '이름: 내림차순 정렬' }) })).toHaveAttribute('aria-sort', 'ascending')
  await expect(page.getByRole('button', { name: '이름: 내림차순 정렬' })).toHaveCSS('outline-width', '2px')
  const firstCheckbox = table.locator('tbody input[type="checkbox"]:enabled').first()
  await firstCheckbox.focus()
  await page.keyboard.press('Space')
  await expect(firstCheckbox).toBeChecked()
  const all = page.getByRole('checkbox', { name: '현재 페이지 전체 선택' })
  expect(await all.evaluate((el: HTMLInputElement) => el.indeterminate)).toBe(true)
  await all.check()
  await expect(all).toBeChecked()
  await expect(page.getByRole('checkbox', { name: '최유진 선택' })).toHaveCount(0) // sorted last page
  await page.getByRole('button', { name: '다음', exact: true }).click()
  await expect(table.locator('tbody tr')).toHaveCount(2)
  await expect(page.getByRole('checkbox', { name: '최유진 선택' })).toBeDisabled()
  await page.getByRole('searchbox', { name: '직원 목록 검색' }).fill('member1@')
  await expect(table.locator('tbody tr')).toHaveCount(1)
  await expect(page.getByRole('checkbox', { name: '김민수 선택' })).toBeChecked()
  await expect(page.getByRole('button', { name: '이전', exact: true })).toBeDisabled()
  await page.getByRole('searchbox').fill('없는 검색 결과')
  await expect(table).toContainText('검색 결과가 없습니다.')
  await expect(page.locator('.ui-data-table-summary')).toContainText('0–0건')
  await page.getByRole('searchbox').fill('')
  await page.getByLabel('페이지당 행', { exact: true }).selectOption('20')
  await expect(table.locator('tbody tr')).toHaveCount(12)
  await page.screenshot({ path: 'test-results/data-table-employees.png', fullPage: true })
})

test('loading, error retry and empty states are distinct', async ({ page }) => {
  await page.goto(story('loading'))
  await expect(page.getByRole('table')).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByRole('searchbox')).toBeDisabled()
  await expect(page.getByRole('button', { name: '이름: 오름차순 정렬' })).toBeDisabled()
  await expect(page.getByRole('checkbox', { name: '현재 페이지 전체 선택' })).toBeDisabled()
  await page.goto(story('error'))
  await expect(page.getByRole('table')).toContainText('직원 목록을 불러오지 못했습니다.')
  await page.getByRole('button', { name: '다시 시도' }).click()
  await expect(page.getByText('다시 시도 요청을 받았습니다.')).toBeVisible()
  await page.goto(story('empty'))
  await expect(page.getByRole('table')).toContainText('등록된 데이터가 없습니다.')
  await expect(page.locator('.ui-data-table-summary')).toContainText('총 0건 중 0–0건')
})

