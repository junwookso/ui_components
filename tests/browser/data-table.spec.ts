test('package CSS and no-Preflight styles preserve native table geometry', async ({ page }) => {
  await page.goto(story('employees'))
  await expect(page.getByRole('table')).toBeVisible()
  const markup = await page.locator('.ui-data-table').evaluate(el => el.outerHTML)
  await page.goto('about:blank')
  await page.setContent(markup)
  await page.addStyleTag({ content: await readFile('.test-consumer/no-reset.css', 'utf8') })
  await expect(page.getByRole('table')).toHaveCSS('border-spacing', '0px')
  await expect(page.locator('caption')).toHaveCSS('font-size', '16px')
  expect((await page.locator('tbody td').first().boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await expect(page.locator('.ui-data-table-checkbox').first()).toHaveCSS('width', '16px')
  await expect(page.locator('.ui-data-table-toolbar')).toHaveCSS('display', 'flex')
  await expect(page.locator('.ui-data-table-sort').first()).toHaveCSS('font-size', '14px')
  await page.emulateMedia({ forcedColors: 'active' })
  await page.locator('tbody tr').first().evaluate(el => el.setAttribute('data-selected', 'true'))
  await expect(page.locator('tbody tr').first().locator('td').first()).toHaveCSS('border-bottom-width', '2px')
  await page.goto('http://127.0.0.1:6008')
  await expect(page.getByRole('table', { name: '배포 테이블' })).toBeVisible()
  await expect(page.getByRole('table').locator('caption')).toHaveCSS('font-size', '16px')
})
