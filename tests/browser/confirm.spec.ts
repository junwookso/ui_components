import { expect, test } from '@playwright/test'
const story = (name = 'playground') => `/iframe.html?id=actions-confirm--${name}&viewMode=story`

test('confirm uses dialog layout, safe focus, keyboard results and focus return', async ({ page }) => {
  await page.goto(story())
  const trigger = page.getByRole('button', { name: '확인 요청 열기' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '변경사항을 저장할까요?' })
  await expect(dialog).toHaveAccessibleDescription('저장한 내용은 팀원에게 바로 반영됩니다.')
  const cancel = dialog.getByRole('button', { name: '취소', exact: true })
  const confirm = dialog.getByRole('button', { name: '확인', exact: true })
  await expect(cancel).toBeFocused()
  await expect(dialog).toHaveCSS('width', '480px')
  await expect(dialog).toHaveCSS('border-radius', '6px')
  const c = (await cancel.boundingBox())!, a = (await confirm.boundingBox())!, d = (await dialog.boundingBox())!
  expect(c.x).toBeLessThan(a.x)
  expect(Math.abs(d.x + d.width - a.x - a.width - 17)).toBeLessThan(1)
  await page.keyboard.press('Enter')
  await expect(page.getByRole('status')).toHaveText('취소했습니다.')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.keyboard.press('Tab')
  await expect(confirm).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('status')).toHaveText('확인했습니다.')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.mouse.click(2, 2)
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('status')).toHaveText('취소했습니다.')
  await expect(trigger).toBeFocused()
  await page.goto(story('backdrop-dismiss'))
  await page.getByRole('button', { name: '확인 요청 열기' }).click()
  await page.mouse.click(2, 2)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('status')).toHaveText('취소했습니다.')
})
